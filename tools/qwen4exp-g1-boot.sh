#!/usr/bin/env bash
# qwen4exp-g1-boot.sh -- gate G1 ("boot + memory fit") box driver for the
# qwen4exp ds4 engine.
#
# The driver runs two legs of the same fixed prompt against the same artifact,
# one after the other, under one GPU lock:
#
#   leg 1  serial   --mtp-draft 1   draft depth 0
#   leg 2  mtp1     --mtp-draft 2   draft depth 1
#
# The MTP head goes to both legs with --mtp-model. The resident set is thus the
# same for both legs, and only the draft depth changes. The depth mapping comes
# from the track fixture, not from this driver:
# serve_configuration.depths.{serial,mtp1}.ds4_mtp_draft_tokens is {1,2}. The
# engine makes a depth from the draft count in
# ds4_qwen4exp_mtp_depth_from_draft_tokens(): depth = draft_tokens - 1.
#
# BOTH LEGS TAKE THE SAME CLI PATH.
# The ds4 CLI has two generation paths (ds4_cli.c, the branch after the
# diagnostic block). A leg with --temp 0 and --mtp-draft 1 satisfies no clause
# of that branch, so it falls to ds4_engine_generate_argmax(), which starts its
# prefill timer BEFORE ds4_session_create() and does no GPU warm-up. A leg with
# --mtp-draft 2 satisfies the draft-tokens clause and goes to
# run_sampled_generation(), which warms the GPU up first and excludes the
# warm-up from the timer. Those two sets of numbers are not comparable.
#
# The driver therefore sets DS4_CLI_FORCE_SESSION=1 on both legs. That is the
# override the CLI provides for this purpose -- its comment says it "exists so
# TP-vs-single-node validation compares like with like" -- and it sends both
# legs through run_sampled_generation(). Both legs then pay the same warm-up,
# exclude it from the same timer, and start the prefill clock at the same point.
# Both stay greedy at --temp 0: the serial leg through the greedy_argmax path,
# the mtp1 leg through ds4_session_sample() at temperature 0.
#
# The driver records, for each leg: the time to the first generated byte, the
# prefill and generation tok/s the engine itself prints, the peak RSS, the GPU
# memory high-water per process at 1 Hz, and the generated stream. It then
# compares the two streams and writes one JSON summary.
#
# MEMORY SAFETY. Nothing loads until all of these hold:
#
#   * each pinned file is present with exactly the byte count the fixture
#     declares (setup.sh owns the sha256 sums; this driver does not re-hash);
#   * the GPU lock is HELD, not only requested;
#   * MemAvailable covers the budget and the headroom. The driver tests this
#     twice: before it waits for the lock, and again with the lock held. The box
#     can fill while the driver waits in the queue.
#
# THE BUDGET. The artifact holds ~103.7 GiB of body and a 2.6 GiB MTP head, but
# the body is not all resident. The per-layer n-gram (PLE) table stays mapped on
# the solid-state disk. The engine puts it in its own family and subtracts it:
#
#   ds4_qwen4exp.inc: plan->ssd_bytes = plan->bytes[DS4_QWEN4EXP_MEM_PLE];
#                     plan->resident_bytes = plan->total_bytes - plan->ssd_bytes;
#
# The driver subtracts the same tensor. It reads the size from the GGUF tensor
# index. It does not guess the size and it does not hold a copy of the number.
# If it counted the table as resident, it would refuse a load that fits. If it
# held a fixed size, it would under-count a different artifact.
#
#   required = body bytes - PLE table bytes    resident weights
#            + MTP head bytes                  resident head
#            + session budget                  KV, state, activations, PLE window
#            + headroom                        10 GiB, the engine's own
#                                              DS4_QWEN4EXP_MEMORY_HEADROOM_BYTES
#
# WATCHDOG. While a leg runs, the driver reads MemAvailable once each second. If
# the value falls below the floor, the driver kills the whole run process group
# and exits non-zero. The engine's own guard acts before the engine allocates.
# This watchdog covers everything after that point.
#
# HALT. The driver puts itself in its own process group and writes its pid and
# its pgid into the run directory. tools/qwen4exp-g1-halt.sh RUNDIR stops the
# driver, both samplers and ds4 from outside.
#
# GATE OVERRIDES. The budget, the headroom and the floor cannot be weakened on a
# real run. A value weaker than the default is refused by name. To test the
# mechanics of the gate itself, pass --mechanics-test. That mode accepts a
# substitute memory source and any budget value, prints a banner, and marks the
# summary. Its results are never a gate result.
#
# EXIT CODES
#   0  both legs ran and the streams agree
#   2  refusal before any load (missing tool, missing file, pin, budget, memory)
#   3  another run holds the GPU lock
#   4  the watchdog killed the run
#   5  a leg exited non-zero
#   6  the serial and mtp1 streams disagree
#   7  a leg generated no tokens (no-output), which is never a pass
set -euo pipefail

REPO_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." >/dev/null && pwd -P)"

# --- own process group ------------------------------------------------------
# The run must be its own process group, so that halt reaches ds4, the watchdog
# and the samplers together, and so that a signal for the run never reaches the
# shell that started it. The driver re-execs itself once under setsid. This
# happens before the arguments are read, so the re-exec carries the caller's
# argv through unchanged. A box without setsid is refused below, because the
# alternative is to write the operator's own process group.
if [ "${QWEN4EXP_G1_SETSID:-0}" != "1" ] && command -v setsid >/dev/null 2>&1; then
  self_pgid="$(ps -o pgid= -p $$ 2>/dev/null | tr -d '[:space:]' || true)"
  if [ "${self_pgid}" != "$$" ]; then
    export QWEN4EXP_G1_SETSID=1
    exec setsid --wait "${BASH_SOURCE[0]}" "$@"
  fi
fi
export QWEN4EXP_G1_SETSID=1

# --- defaults ---------------------------------------------------------------
BUILD_DIR=""
ARTIFACT_DIR=""
RUN_ROOT=""
DRY_RUN=0
MECHANICS_TEST=0
# The golden's prompt prefix. See the note above leg_cmd.
PROMPT_TOKENS=1024
TOKENS=64
CTX=4096
PROMPT_FILE="${REPO_DIR}/correctness_prompts/public_longcopy_gate_english_1024.txt"
FIXTURE="${REPO_DIR}/fixtures/qwen3_8_125b_a6b_track.json"
LOCK_PATH=/tmp/mtplx-gpu-exclusive.lock
LOCK_WAIT=600
MEMINFO=/proc/meminfo

# The floors of the budget. A real run may raise any of these and may not lower
# any of them.
#   headroom  10 GiB, the engine's own DS4_QWEN4EXP_MEMORY_HEADROOM_BYTES. The
#             driver's gate and the engine's gate then agree.
#   session   KV and GDN recurrent state, the indexer tape, the dilated PLE
#             convolution window, and the activations of one forward. The engine
#             sizes this exactly in ds4_qwen4exp_session_plan_compute(n_ctx,
#             n_batch). At context 4096 every term is well under 2 GiB, so 4 GiB
#             is a deliberate over-statement. Raise it for a longer context.
#   floor     the watchdog floor on MemAvailable.
MIN_HEADROOM_GIB=10
MIN_SESSION_GIB=4
MIN_FLOOR_GIB=8
HEADROOM_GIB="${MIN_HEADROOM_GIB}"
SESSION_GIB="${MIN_SESSION_GIB}"
FLOOR_GIB="${MIN_FLOOR_GIB}"

usage() {
  cat <<'EOF'
usage: qwen4exp-g1-boot.sh --build DIR --artifact DIR [options]

  --build DIR          built ds4 tree, which must hold an executable ds4
  --artifact DIR       directory of the pinned GGUF shards and the MTP head
  --run-dir DIR        parent of the timestamped run directory
                       (default: <build>/g1-runs)
  --dry-run            print the exact ds4 command lines and stop. Takes no
                       lock, reads no memory, loads nothing
  --tokens N           generated tokens for each leg (default 64)
  --prompt-tokens N    prompt-token prefix each leg sends (default 1024, the
                       golden's prefix; the prompt file tokenizes to 1054)
  --ctx N              allocated context tokens (default 4096)
  --prompt FILE        prompt file (default: the public correctness prompt)
  --fixture FILE       track fixture with target.files (default: this repo's)
  --session-gib N      session, KV and scratch budget (default and minimum 4)
  --headroom-gib N     refusal headroom (default and minimum 10)
  --floor-gib N        watchdog MemAvailable floor (default and minimum 8)
  --lock PATH          GPU lock (default /tmp/mtplx-gpu-exclusive.lock)
  --lock-wait SEC      seconds to wait for the lock (default 600)
  --mechanics-test     test the mechanics of the gate itself. Removes the
                       minimums above and permits --meminfo. The summary names
                       the mode. Results are not gate results
  --meminfo FILE       substitute memory source. --mechanics-test only
  -h, --help           this text
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --build)          BUILD_DIR="$2"; shift 2 ;;
    --artifact)       ARTIFACT_DIR="$2"; shift 2 ;;
    --run-dir)        RUN_ROOT="$2"; shift 2 ;;
    --dry-run)        DRY_RUN=1; shift ;;
    --mechanics-test) MECHANICS_TEST=1; shift ;;
    --tokens)         TOKENS="$2"; shift 2 ;;
    --prompt-tokens)  PROMPT_TOKENS="$2"; shift 2 ;;
    --ctx)            CTX="$2"; shift 2 ;;
    --prompt)         PROMPT_FILE="$2"; shift 2 ;;
    --fixture)        FIXTURE="$2"; shift 2 ;;
    --session-gib)    SESSION_GIB="$2"; shift 2 ;;
    --headroom-gib)   HEADROOM_GIB="$2"; shift 2 ;;
    --floor-gib)      FLOOR_GIB="$2"; shift 2 ;;
    --lock)           LOCK_PATH="$2"; shift 2 ;;
    --lock-wait)      LOCK_WAIT="$2"; shift 2 ;;
    --meminfo)        MEMINFO="$2"; shift 2 ;;
    -h|--help)        usage; exit 0 ;;
    *) printf 'qwen4exp-g1-boot: unknown argument %s\n' "$1" >&2; usage >&2; exit 2 ;;
  esac
done

GIB=1073741824

refuse() { # refuse NAME MESSAGE...
  local name="$1"; shift
  printf 'qwen4exp-g1-boot: REFUSE %s: %s\n' "${name}" "$*" >&2
  exit 2
}

[ -n "${BUILD_DIR}" ]    || refuse missing-argument "--build DIR is required"
[ -n "${ARTIFACT_DIR}" ] || refuse missing-argument "--artifact DIR is required"

is_uint() { case "$1" in ''|*[!0-9]*) return 1 ;; *) return 0 ;; esac; }
for pair in "TOKENS:${TOKENS}" "CTX:${CTX}" "LOCK_WAIT:${LOCK_WAIT}" \
            "SESSION_GIB:${SESSION_GIB}" "HEADROOM_GIB:${HEADROOM_GIB}" "FLOOR_GIB:${FLOOR_GIB}"; do
  is_uint "${pair#*:}" || refuse bad-argument "${pair%%:*} must be a non-negative integer, got '${pair#*:}'"
done

# --- gate overrides ---------------------------------------------------------
# A real run cannot weaken its own gate. Only --mechanics-test lifts the
# minimums, and it says so in every place the run is reported.
if [ "${MECHANICS_TEST}" -eq 1 ]; then
  printf 'qwen4exp-g1-boot: MECHANICS TEST -- the budget minimums are lifted and the memory source may be substituted. This run is not a gate result.\n' >&2
else
  [ "${MEMINFO}" = "/proc/meminfo" ] \
    || refuse gate-override "--meminfo needs --mechanics-test; a real run reads /proc/meminfo"
  [ "${HEADROOM_GIB}" -ge "${MIN_HEADROOM_GIB}" ] \
    || refuse gate-override "--headroom-gib ${HEADROOM_GIB} is below the engine's own ${MIN_HEADROOM_GIB} GiB headroom; a real run may raise it, never lower it"
  [ "${SESSION_GIB}" -ge "${MIN_SESSION_GIB}" ] \
    || refuse gate-override "--session-gib ${SESSION_GIB} is below the ${MIN_SESSION_GIB} GiB session budget; a real run may raise it, never lower it"
  [ "${FLOOR_GIB}" -ge "${MIN_FLOOR_GIB}" ] \
    || refuse gate-override "--floor-gib ${FLOOR_GIB} is below the ${MIN_FLOOR_GIB} GiB watchdog floor; a real run may raise it, never lower it"
fi

# --- tools ------------------------------------------------------------------
# Each of these carries a deliverable or a safety property. A missing one is a
# refusal by name, not a silently absent field in the summary.
need_tool() { # need_tool PATH_OR_NAME WHAT_IT_IS_FOR
  if [ "${1#/}" != "$1" ]; then
    [ -x "$1" ] || refuse missing-tool "$1 is required for $2"
  else
    command -v "$1" >/dev/null 2>&1 || refuse missing-tool "$1 is required for $2"
  fi
}
need_tool python3      "reading the fixture and the GGUF tensor index"
need_tool /usr/bin/time "the peak RSS of each leg"
need_tool sha256sum    "identifying each leg's generated stream"
need_tool nvidia-smi   "the GPU memory high-water of each leg"
need_tool flock        "holding the GPU lock"
need_tool pgrep        "finding the run's processes for the watchdog and for halt"
need_tool stdbuf       "unbuffering the generated bytes, without which the time to first token is a flush boundary"
need_tool setsid       "putting the run in its own process group; without it halt would have to signal the operator's group"

DS4_BIN="${BUILD_DIR%/}/ds4"
[ -x "${DS4_BIN}" ]     || refuse missing-engine "no executable ds4 at ${DS4_BIN}"
[ -r "${PROMPT_FILE}" ] || refuse missing-prompt "cannot read the prompt file ${PROMPT_FILE}"
[ -r "${FIXTURE}" ]     || refuse missing-fixture "cannot read the track fixture ${FIXTURE}"

# --- pins -------------------------------------------------------------------
# setup.sh owns the sha256 verification of these files. The driver asserts that
# each file on disk still has exactly the pinned size, so a truncated or a
# swapped shard cannot reach a load. The shard names and the head name come from
# the fixture, not from a pattern of the driver's own.
PIN_REPORT="$(python3 - "${FIXTURE}" "${ARTIFACT_DIR}" <<'PY'
import json, os, sys
fixture, art = sys.argv[1], sys.argv[2]
files = json.load(open(fixture))["target"]["files"]
shards, head, bad = [], None, []
for f in files:
    p = os.path.join(art, f["path"])
    if not os.path.exists(p):
        bad.append(f"{f['path']}: missing")
        continue
    got = os.path.getsize(p)
    if got != f["bytes"]:
        bad.append(f"{f['path']}: {got} bytes on disk, fixture pins {f['bytes']}")
    if "-of-" in f["path"]:
        shards.append((f["path"], got))
    else:
        head = (f["path"], got)
if bad:
    print("BAD"); print("\n".join(bad)); raise SystemExit(0)
if not shards or head is None:
    print("BAD"); print("the fixture names no sharded body or no MTP head"); raise SystemExit(0)
shards.sort()
print("OK")
print(os.path.join(art, shards[0][0]))
print(os.path.join(art, head[0]))
print(sum(b for _, b in shards))
print(head[1])
PY
)" || refuse fixture-read "cannot read target.files out of ${FIXTURE}"

if [ "$(printf '%s\n' "${PIN_REPORT}" | head -1)" != "OK" ]; then
  refuse pin-mismatch "$(printf '%s\n' "${PIN_REPORT}" | tail -n +2 | tr '\n' ';')"
fi
MODEL_SHARD1="$(printf '%s\n' "${PIN_REPORT}" | sed -n 2p)"
MTP_PATH="$(printf '%s\n' "${PIN_REPORT}" | sed -n 3p)"
BODY_BYTES="$(printf '%s\n' "${PIN_REPORT}" | sed -n 4p)"
HEAD_BYTES="$(printf '%s\n' "${PIN_REPORT}" | sed -n 5p)"

# --- the PLE table, from the GGUF tensor index ------------------------------
# per_layer_token_embd.weight is the n-gram table. The engine puts it in
# DS4_QWEN4EXP_MEM_PLE and subtracts it from the resident total. So does the
# driver. The reader below opens only GGUF headers. The tensor index sits at the
# front of each shard, so no weight byte is read.
#
# The driver holds no copy of the engine's type table. It reads the one type the
# fixture pins for this tensor (target.quantization.ple_table) and refuses when
# the file disagrees with the pin. The block geometry of that type is checked
# against the file: a wrong pair would not divide the tensor evenly.
PLE_BYTES="$(python3 - "${MODEL_SHARD1}" "${FIXTURE}" <<'PY'
import json, os, re, struct, sys

# The pinned quantization of the PLE table, and its GGUF block geometry. This is
# one entry, for the one tensor the driver sizes -- not a copy of the engine's
# gguf_types[]. ds4.c records the same pair with the same derivation: "IQ4_NL is
# 32 values per block in 18 bytes: one f16 scale and 16 packed nibbles."
# This reader is superseded by tools/gguf-tensor-bytes.py when PR #91 lands.
GEOMETRY = {"IQ4_NL": (20, 32, 18)}

def rd(f, n):
    b = f.read(n)
    if len(b) != n: raise SystemExit("gguf: short read")
    return b
def u32(f): return struct.unpack("<I", rd(f, 4))[0]
def u64(f): return struct.unpack("<Q", rd(f, 8))[0]
def st(f):  return rd(f, u64(f)).decode("utf-8", "replace")

def skip_value(f, t):
    if   t in (0, 1, 7):    rd(f, 1)
    elif t in (2, 3):       rd(f, 2)
    elif t in (4, 5, 6):    rd(f, 4)
    elif t in (10, 11, 12): rd(f, 8)
    elif t == 8:            st(f)
    elif t == 9:
        et = u32(f)
        for _ in range(u64(f)): skip_value(f, et)
    else: raise SystemExit(f"gguf: unknown metadata type {t}")

def scan(path, want_id, blk, size):
    with open(path, "rb") as f:
        if rd(f, 4) != b"GGUF": raise SystemExit(f"gguf: {path} is not a GGUF file")
        u32(f)
        n_tensors, n_kv = u64(f), u64(f)
        for _ in range(n_kv):
            st(f); skip_value(f, u32(f))
        for _ in range(n_tensors):
            name = st(f)
            dims = [u64(f) for _ in range(u32(f))]
            ttype = u32(f); u64(f)
            if name != "per_layer_token_embd.weight":
                continue
            if ttype != want_id:
                raise SystemExit(f"gguf: {name} is type {ttype}, the fixture pins type {want_id}")
            n = 1
            for d in dims: n *= d
            if n % blk:
                raise SystemExit(f"gguf: {name} holds {n} values, which is not a whole number of {blk}-value blocks")
            return n // blk * size
    return None

first, fixture = sys.argv[1], sys.argv[2]
pin = json.load(open(fixture))["target"]["quantization"]["ple_table"]
if pin not in GEOMETRY:
    raise SystemExit(f"gguf: the fixture pins the PLE table as {pin}, whose block geometry this driver does not carry")
want_id, blk, size = GEOMETRY[pin]

m = re.match(r"(.*)-(\d{5})-of-(\d{5})\.gguf$", os.path.basename(first))
d = os.path.dirname(first) or "."
paths = [first]
if m:
    stem, total = m.group(1), int(m.group(3))
    paths = [os.path.join(d, f"{stem}-{i:05d}-of-{total:05d}.gguf") for i in range(1, total + 1)]
for p in paths:
    if not os.path.exists(p): raise SystemExit(f"gguf: missing shard {p}")
    b = scan(p, want_id, blk, size)
    if b is not None:
        print(b); raise SystemExit(0)
raise SystemExit("gguf: no per_layer_token_embd.weight in any shard")
PY
)" || refuse ple-unreadable "cannot size per_layer_token_embd.weight from the artifact's GGUF index"

RESIDENT_BYTES=$(( BODY_BYTES - PLE_BYTES ))
SESSION_BYTES=$(( SESSION_GIB * GIB ))
HEADROOM_BYTES=$(( HEADROOM_GIB * GIB ))
FLOOR_KB=$(( FLOOR_GIB * 1024 * 1024 ))
REQUIRED_BYTES=$(( RESIDENT_BYTES + HEAD_BYTES + SESSION_BYTES + HEADROOM_BYTES ))

gib() { awk -v b="$1" 'BEGIN{printf "%.2f", b/1073741824}'; }

# --- the exact commands -----------------------------------------------------
# Every flag comes from the argument loop of ds4_cli.c:
#   -m/--model FILE   shard 00001. model_open() maps the whole -of- family
#   --mtp-model FILE  the external support GGUF. support_model_detect() reads a
#                     qwen4exp nextn head and weights_bind_qwen4exp_mtp() binds
#                     it. --mtp is the wrong flag here: it means an embedded
#                     head and refuses by name for this family
#   --mtp-draft N     the draft-token count. depth = N - 1
#   --prompt-file F   run one long prompt from a file and stop
#   -n/--tokens N     the largest number of generated tokens
#   --temp 0          greedy
#   -c/--ctx N        allocated context tokens
#   --cuda            select the CUDA backend
#   --raw-prompt      send the prompt file's own tokens unchanged. Qwen3.8 Flash
#                     Next has no chat template (no user/assistant/system
#                     markers), and the engine refuses to wrap a prompt without
#                     one. The public correctness prompt is raw text by design.
# DS4_CLI_FORCE_SESSION sends both legs through run_sampled_generation(). See
# the note at the top of this file.
#
# --prompt-tokens IS NOT A TUNING KNOB. The golden is the first 1024 tokens of
# the prompt file, and the file tokenizes to 1054. Without this the CLI decodes
# all 1054 and its first argmax on the full instruction is EOS -- so the leg
# generates nothing and the run compares two empty streams. Both legs send the
# same prefix the golden was authored on, or the comparison is not the golden's.
leg_cmd() { # leg_cmd DRAFT_TOKENS -- prints the argv, one word to a line
  printf '%s\n' \
    env DS4_CLI_FORCE_SESSION=1 \
    "${DS4_BIN}" --cuda --raw-prompt \
    -m "${MODEL_SHARD1}" \
    --mtp-model "${MTP_PATH}" \
    --mtp-draft "$1" \
    --prompt-file "${PROMPT_FILE}" \
    --prompt-tokens "${PROMPT_TOKENS}" \
    -n "${TOKENS}" \
    --temp 0 \
    -c "${CTX}"
}
leg_cmd_line() { leg_cmd "$1" | sed "s/'/'\\\\''/g; s/^/'/; s/\$/'/" | tr '\n' ' '; }

if [ "${DRY_RUN}" -eq 1 ]; then
  cat <<EOF
qwen4exp-g1-boot: dry run -- nothing is locked, nothing is loaded.

  build     ${BUILD_DIR}
  artifact  ${ARTIFACT_DIR}
  prompt    ${PROMPT_FILE}
  fixture   ${FIXTURE}

memory plan
  body (4 shards)      $(gib "${BODY_BYTES}") GiB
  PLE table (SSD)     -$(gib "${PLE_BYTES}") GiB   per_layer_token_embd.weight, mapped, never resident
  resident weights     $(gib "${RESIDENT_BYTES}") GiB
  MTP head             $(gib "${HEAD_BYTES}") GiB
  session/KV/scratch   $(gib "${SESSION_BYTES}") GiB
  headroom             $(gib "${HEADROOM_BYTES}") GiB
  required             $(gib "${REQUIRED_BYTES}") GiB
  watchdog floor       ${FLOOR_GIB} GiB MemAvailable

leg 1 -- serial, draft depth 0
  $(leg_cmd_line 1)

leg 2 -- mtp1, draft depth 1
  $(leg_cmd_line 2)
EOF
  exit 0
fi

# --- run directory ----------------------------------------------------------
RUN_ROOT="${RUN_ROOT:-${BUILD_DIR%/}/g1-runs}"
RUN="${RUN_ROOT%/}/$(date -u +%Y%m%dT%H%M%SZ)-g1"
mkdir -p "${RUN}"
LOG="${RUN}/driver.log"
log() { printf '[%s] %s\n' "$(date -u +%H:%M:%SZ)" "$*" | tee -a "${LOG}"; }

printf '%s\n' "$$" > "${RUN}/run.pid"
ps -o pgid= -p $$ 2>/dev/null | tr -d '[:space:]' > "${RUN}/run.pgid" || true

[ "${MECHANICS_TEST}" -eq 1 ] && log "MECHANICS TEST -- not a gate result"
log "run dir ${RUN}"
log "engine ${DS4_BIN}"
log "artifact ${ARTIFACT_DIR}"
log "pins OK: body $(gib "${BODY_BYTES}") GiB over the fixture's shard list, head $(gib "${HEAD_BYTES}") GiB"
log "memory plan: resident $(gib "${RESIDENT_BYTES}") GiB (body minus the $(gib "${PLE_BYTES}") GiB SSD-resident PLE table) + head $(gib "${HEAD_BYTES}") GiB + session $(gib "${SESSION_BYTES}") GiB + headroom $(gib "${HEADROOM_BYTES}") GiB = $(gib "${REQUIRED_BYTES}") GiB required"

read_avail_kb() {
  local kb
  [ -r "${MEMINFO}" ] || return 1
  kb="$(awk '/^MemAvailable:/ {print $2; exit}' "${MEMINFO}")"
  [ -n "${kb}" ] || return 1
  printf '%s\n' "${kb}"
}

memory_gate() { # memory_gate WHEN
  local kb bytes
  kb="$(read_avail_kb)" \
    || { printf 'qwen4exp-g1-boot: REFUSE memory-unreadable: %s carries no MemAvailable line; refusing to start a %s GiB load blind (%s)\n' "${MEMINFO}" "$(gib "${REQUIRED_BYTES}")" "$1" >&2; exit 2; }
  bytes=$(( kb * 1024 ))
  if [ "${bytes}" -lt "${REQUIRED_BYTES}" ]; then
    printf 'qwen4exp-g1-boot: REFUSE memory-fit: the boot needs %s GiB (resident %s + head %s + session %s + headroom %s) and %s reports %s GiB available (%s). Nothing has been loaded.\n' \
      "$(gib "${REQUIRED_BYTES}")" "$(gib "${RESIDENT_BYTES}")" "$(gib "${HEAD_BYTES}")" \
      "$(gib "${SESSION_BYTES}")" "$(gib "${HEADROOM_BYTES}")" "${MEMINFO}" "$(gib "${bytes}")" "$1" \
      | tee -a "${LOG}" >&2
    exit 2
  fi
  log "memory gate (${1}): $(gib "${bytes}") GiB available, $(gib "${REQUIRED_BYTES}") GiB required -- ok"
}

# Before the lock: refuse at once rather than wait in a queue for a load that
# cannot fit.
memory_gate "before the lock"

# --- GPU lock ---------------------------------------------------------------
exec 9>>"${LOCK_PATH}" || refuse lock-unwritable "cannot open the GPU lock ${LOCK_PATH}"
