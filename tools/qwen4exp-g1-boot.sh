# --- the run process group --------------------------------------------------
# Nothing the driver starts outlives it: not ds4, not a ds4 grandchild, not a
# sampler. The driver leads its own process group, so the group is the run. The
# function kills every member except this shell, which still has a summary to
# write and an exit code to report. The watchdog and the exit trap both use it.
kill_run_group() {
  local pids
  pids="$(pgrep -g "$$" 2>/dev/null | grep -v "^$$\$" || true)"
  if [ -n "${pids}" ]; then
    # Deliberate word splitting: pids is a newline-separated list.
    # shellcheck disable=SC2086
    kill -KILL ${pids} 2>/dev/null || true
  fi
}
trap kill_run_group EXIT

WATCHDOG_TRIPPED=0

# Liveness of a child, for the loop and for the watchdog.
# The state field of /proc/PID/stat is the test, not a signal. A child that has
# exited but is not yet reaped is a zombie, and a signal test on a zombie
# succeeds; the state field reports Z and this returns false. In practice the
# shell reaps a background job soon enough that a signal test usually agrees,
# so this is the stricter of two tests rather than the only correct one. The
# comm field can hold spaces and parentheses, so the state is read after the
# last ")".
leg_alive() {
  local line st
  line="$(cat "/proc/$1/stat" 2>/dev/null)" || return 1
  st="${line##*) }"
  st="${st%% *}"
  [ -n "${st}" ] && [ "${st}" != "Z" ]
}

# Read the engine's timing line out of a stderr capture and print shell
# assignments for the caller to eval. Its own function so it can be tested
# against a synthetic engine without a GPU, an artifact or Linux
# (tools/test-qwen4exp-g1-no-output.sh sources exactly this function).
#
# Prints, always, one assignment per name: prefill, decode, prompt_tok,
# prefill_s, gen_tok, decode_s. A value the line does not carry prints empty.
g1_parse_rates() { # g1_parse_rates STDERR_FILE
  local err="$1" line
  local prefill decode prompt_tok prefill_s gen_tok decode_s
  prefill="$(sed -n 's/.*prefill: \([0-9.]*\) t\/s.*/\1/p' "${err}" 2>/dev/null | tail -1)"
  decode="$(sed -n 's/.*generation: \([0-9.]*\) t\/s.*/\1/p' "${err}" 2>/dev/null | tail -1)"
  # The NEW shape alone carries the counts and the per-phase seconds.
  line="$(grep -E 'generation: [0-9.]+ t/s \([0-9]+ prompt tokens in' "${err}" 2>/dev/null | tail -1 || true)"
  if [ -n "${line}" ]; then
    prompt_tok="$(printf '%s\n' "${line}" | sed -n 's/.*(\([0-9]*\) prompt tokens in .*/\1/p')"
    prefill_s="$(printf '%s\n' "${line}" | sed -n 's/.*prompt tokens in \([0-9.]*\) s,.*/\1/p')"
    gen_tok="$(printf '%s\n' "${line}" | sed -n 's/.*, \([0-9]*\) generated in .*/\1/p')"
    decode_s="$(printf '%s\n' "${line}" | sed -n 's/.*generated in \([0-9.]*\) s).*/\1/p')"
  fi
  printf 'prefill=%s\ndecode=%s\nprompt_tok=%s\nprefill_s=%s\ngen_tok=%s\ndecode_s=%s\n' \
    "${prefill}" "${decode}" "${prompt_tok:-}" "${prefill_s:-}" "${gen_tok:-}" "${decode_s:-}"
}

# THE GENERATED STREAM, which is not the same thing as stdout.
#
# The engine prints its memory plan and then a budget line before the first
# token, and that budget line carries a LIVE reading:
#
#   qwen4exp memory budget: free 119.01 GiB ...   (serial)
#   qwen4exp memory budget: free 118.64 GiB ...   (mtp1)
#
# Hashing stdout whole made the two legs differ on that number alone. The first
# real run on 3751b81 reported stream_mismatch with a stream.diff whose only
# hunk was those two lines, while every generated token was byte-identical --
# a preamble reading a machine's free memory is not a token stream.
#
# So: drop everything through the LAST budget line and compare what follows. The
# raw stdout stays on disk untouched; this writes the stripped stream beside it.
# An engine that prints no budget line at all is compared whole, which is the
# old behaviour and the safe direction -- it can only report a difference that
# is really there.
g1_strip_preamble() { # g1_strip_preamble RAW_STDOUT STREAM_OUT
  local raw="$1" out="$2" last
  last="$(grep -n 'qwen4exp memory budget:' "${raw}" 2>/dev/null | tail -1 | cut -d: -f1)"
  if [ -n "${last}" ]; then
    tail -n +"$(( last + 1 ))" "${raw}" > "${out}"
  else
    cat "${raw}" > "${out}"
  fi
}

# The no-output verdict, as its own function for the same reason. Prints the
# reason, or nothing when the leg produced tokens.
#
# IT MUST BE GIVEN THE STRIPPED STREAM, never raw stdout. The preamble is always
# there, so raw stdout always carries non-whitespace and the text fallback could
# never fire -- exactly the "a banner does not rescue a leg" case it exists for.
g1_no_output_reason() { # g1_no_output_reason GENERATED_TOKENS STDOUT_FILE
  local gen="$1" out="$2"
  if [ -n "${gen}" ] && [ "${gen}" -eq 0 ] 2>/dev/null; then
    printf '0 generated tokens\n'
  elif ! grep -q '[^[:space:]]' "${out}" 2>/dev/null; then
    printf 'no token text on stdout\n'
  fi
}

run_leg() { # run_leg NAME DRAFT_TOKENS
  local name="$1" draft="$2"
  local out="${RUN}/${name}.stdout" err="${RUN}/${name}.stderr"
  local tm="${RUN}/${name}.time" gpu="${RUN}/${name}.gpu.csv" mem="${RUN}/${name}.mem.log"
  local -a cmd=()
  local line
  while IFS= read -r line; do cmd+=("${line}"); done < <(leg_cmd "${draft}")

  : > "${out}"; : > "${err}"; : > "${gpu}"; : > "${mem}"
  log "leg ${name}: $(leg_cmd_line "${draft}")"

  local t0 ttft="" hwm_kb=0 gpu_peak=0 leg_pid
  t0="$(date +%s.%N)"

  # stdbuf keeps the generated bytes unbuffered, so the first-byte stamp is the
  # real time to first token and not a 4 KiB flush boundary.
  /usr/bin/time -v -o "${tm}" stdbuf -o0 "${cmd[@]}" > "${out}" 2> "${err}" &
  leg_pid=$!
  printf '%s\n' "${leg_pid}" > "${RUN}/${name}.pid"

  local tick=0 ds4pid="" kb rss hwm g mine
  while leg_alive "${leg_pid}"; do
    if [ -z "${ttft}" ] && [ -s "${out}" ]; then
      ttft="$(awk -v a="$(date +%s.%N)" -v b="${t0}" 'BEGIN{printf "%.3f", a-b}')"
      log "leg ${name}: first generated byte at ${ttft} s"
    fi
    if [ $(( tick % 20 )) -eq 0 ]; then
      kb="$(read_avail_kb || echo 0)"
      [ -z "${ds4pid}" ] && ds4pid="$(pgrep -P "${leg_pid}" 2>/dev/null | head -1 || true)"
      rss=0; hwm=0
      if [ -n "${ds4pid}" ] && [ -r "/proc/${ds4pid}/status" ]; then
        rss="$(awk '/^VmRSS:/ {print $2; exit}' "/proc/${ds4pid}/status" 2>/dev/null || echo 0)"
        hwm="$(awk '/^VmHWM:/ {print $2; exit}' "/proc/${ds4pid}/status" 2>/dev/null || echo 0)"
      fi
      [ "${hwm:-0}" -gt "${hwm_kb}" ] 2>/dev/null && hwm_kb="${hwm}"
      printf '%s avail_kB=%s rss_kB=%s hwm_kB=%s\n' "$(date -u +%H:%M:%SZ)" "${kb}" "${rss:-0}" "${hwm:-0}" >> "${mem}"

      # The GPU memory of each process, once a second. On a unified-memory box
      # the per-GPU totals read N/A, so the compute-apps view is the one that
      # reports.
      g="$(nvidia-smi --query-compute-apps=pid,used_gpu_memory --format=csv,noheader,nounits 2>/dev/null || true)"
      if [ -n "${g}" ]; then
        printf '%s,%s\n' "$(date -u +%H:%M:%SZ)" "$(printf '%s' "${g}" | tr '\n' ';')" >> "${gpu}"
        mine="$(printf '%s\n' "${g}" | awk -F', *' -v p="${ds4pid:-0}" '$1==p {print $2}' | sort -n | tail -1)"
        [ -n "${mine}" ] && [ "${mine}" -gt "${gpu_peak}" ] 2>/dev/null && gpu_peak="${mine}"
      fi

      # The trip. The liveness re-check matters: the samples above take tens of
      # milliseconds, mostly in the nvidia-smi call, and a leg can end normally
      # inside that window. Without the re-check a reading taken after a clean
      # exit would turn a good run into a kill.
      if [ "${kb}" -gt 0 ] 2>/dev/null && [ "${kb}" -lt "${FLOOR_KB}" ]; then
        if leg_alive "${leg_pid}"; then
          WATCHDOG_TRIPPED=1
          printf 'qwen4exp-g1-boot: WATCHDOG: MemAvailable %s kB is below the %s GiB floor; killing the run process group\n' "${kb}" "${FLOOR_GIB}" | tee -a "${LOG}" >&2
          kill_run_group
          break
        fi
        log "leg ${name}: MemAvailable ${kb} kB is below the floor, but the leg has already exited; not tripping"
      fi
    fi
    tick=$(( tick + 1 ))
    sleep 0.05
  done

  local rc=0
  wait "${leg_pid}" 2>/dev/null || rc=$?
  [ "${WATCHDOG_TRIPPED}" -eq 1 ] && return 4

  # A leg short enough to end inside one poll interval leaves no first-byte
  # stamp. Report the whole leg as an upper bound rather than nothing, and say
  # which it is, so a bound is never read as a measurement.
  local ttft_bounded=false wall
  wall="$(awk -v a="$(date +%s.%N)" -v b="${t0}" 'BEGIN{printf "%.3f", a-b}')"
  if [ -z "${ttft}" ] && [ -s "${out}" ]; then
    ttft="${wall}"
    ttft_bounded=true
    log "leg ${name}: ended inside one poll interval; the time to first byte is an upper bound of ${ttft} s"
  fi

  # The engine's own timing line, in either shape it has had:
  #
  #   OLD  "ds4: prefill: %.2f t/s, generation: %.2f t/s"
  #   NEW  "... generation: %.2f t/s (%d prompt tokens in %.2f s, %d generated in %.2f s)"
  #
  # Both are parsed, because the new one arrives with a vendor-sync and this
  # driver must read a tree from either side of it. The rates come from either;
  # THE COUNTS COME ONLY FROM THE NEW SHAPE and stay null on the old one, which
  # is why the no-output check below does not rest on them alone.
  local prefill decode maxrss gen_tok prompt_tok prefill_s decode_s
  eval "$(g1_parse_rates "${err}")"
  maxrss="$(sed -n 's/.*Maximum resident set size (kbytes): *\([0-9]*\).*/\1/p' "${tm}" 2>/dev/null | tail -1)"
  [ -n "${maxrss}" ] || maxrss="${hwm_kb}"

  # NO OUTPUT IS A NAMED FAILURE, NOT A STREAM MISMATCH AND NEVER A PASS.
  #
  # A leg that generates nothing used to reach the verdict two ways, and both
  # were wrong. With empty stdout the stream comparison never ran and the gate
  # reported stream_mismatch, which points at divergence when the truth is that
  # there is no stream at all. Worse, two legs that both emitted only a banner
  # compared BYTE-IDENTICAL and the gate reported ok -- a zero-output regression
  # reading as a pass, which is exactly how one got through on 278b799.
  #
  # Two independent signals, because neither covers the other: the engine's own
  # count is authoritative but absent on the old line shape, and the stdout text
  # is always there but cannot distinguish a short generation from none.
  # The generated stream, beside the raw capture, and what everything below
  # compares and hashes.
  local stream="${RUN}/${name}.stream"
  g1_strip_preamble "${out}" "${stream}"

  local no_output_reason
  no_output_reason="$(g1_no_output_reason "${gen_tok:-}" "${stream}")"

  cat > "${RUN}/${name}.json" <<EOF
{
  "leg": "${name}",
  "mtp_draft_tokens": ${draft},
  "draft_depth": $(( draft - 1 )),
  "cli_path": "run_sampled_generation (DS4_CLI_FORCE_SESSION=1)",
  "exit_code": ${rc},
  "time_to_first_byte_s": ${ttft:-null},
  "time_to_first_byte_is_upper_bound": ${ttft_bounded},
  "wall_s": ${wall},
  "prefill_tok_s": ${prefill:-null},
  "decode_tok_s": ${decode:-null},
  "prompt_tokens": ${prompt_tok:-null},
  "generated_tokens": ${gen_tok:-null},
  "prefill_s": ${prefill_s:-null},
  "decode_s": ${decode_s:-null},
  "no_output_reason": $( [ -n "${no_output_reason}" ] && printf '"%s"' "${no_output_reason}" || printf null ),
  "peak_rss_kb": ${maxrss:-0},
  "gpu_peak_mib": ${gpu_peak:-0},
  "stdout_sha256": "$(sha256sum "${out}" | cut -d' ' -f1)",
  "stdout_bytes": $(wc -c < "${out}" | tr -d '[:space:]'),
  "stream_sha256": "$(sha256sum "${stream}" | cut -d' ' -f1)",
  "stream_bytes": $(wc -c < "${stream}" | tr -d '[:space:]')
}
EOF
  log "leg ${name}: exit ${rc}, ttft ${ttft:-n/a} s, prefill ${prefill:-n/a} tok/s, decode ${decode:-n/a} tok/s, ${gen_tok:-n/a} generated from ${prompt_tok:-n/a} prompt tokens, peak RSS ${maxrss:-0} kB, GPU peak ${gpu_peak:-0} MiB"
  if [ -n "${no_output_reason}" ]; then
    log "leg ${name}: no-output: ${no_output_reason}"
    return 7
  fi
  return "${rc}"
}

SERIAL_RC=0; run_leg serial 1 || SERIAL_RC=$?
MTP_RC=0
if [ "${SERIAL_RC}" -eq 0 ]; then
  run_leg mtp1 2 || MTP_RC=$?
else
  log "leg serial exited ${SERIAL_RC}; the mtp1 leg does not start"
fi

# --- streams ----------------------------------------------------------------
# The comparison is over the GENERATED STREAMS, not raw stdout: see
# g1_strip_preamble. The raw captures stay on disk either way.
STREAMS_MATCH=null
if [ -s "${RUN}/serial.stream" ] && [ -s "${RUN}/mtp1.stream" ]; then
  if cmp -s "${RUN}/serial.stream" "${RUN}/mtp1.stream"; then
    STREAMS_MATCH=true
    log "streams: serial and mtp1 are byte-identical (generated stream, preamble stripped)"
  else
    STREAMS_MATCH=false
    diff -u "${RUN}/serial.stream" "${RUN}/mtp1.stream" > "${RUN}/stream.diff" 2>&1 || true
    log "streams: serial and mtp1 DIFFER; see ${RUN}/stream.diff"
  fi
fi

STATUS=ok
EXIT=0
if [ "${WATCHDOG_TRIPPED}" -eq 1 ]; then STATUS=watchdog_kill; EXIT=4
elif [ "${SERIAL_RC}" -eq 7 ] || [ "${MTP_RC}" -eq 7 ]; then STATUS=no_output; EXIT=7
elif [ "${SERIAL_RC}" -ne 0 ] || [ "${MTP_RC}" -ne 0 ]; then STATUS=leg_failed; EXIT=5
elif [ "${STREAMS_MATCH}" != "true" ]; then STATUS=stream_mismatch; EXIT=6
fi

python3 - "${RUN}" <<PY > "${RUN}/g1-summary.json"
